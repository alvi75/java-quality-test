import java.util.*;

class Problem {
    /**
     * Check if it is possible to split the given integer array into two non-empty arrays
     * with the same average.
     *
     * >>> splitArraySameAverage(new int[]{1,2,3,4,5,6,7,8})
     * true
     *
     * >>> splitArraySameAverage(new int[]{3,1})
     * false
     */
    public boolean splitArraySameAverage(int[] nums){
        int n = nums.length;
        int sum = 0;
        for (int num : nums) {
            sum += num;
        }
        for (int i = 1; i < n; i++) {
            if ((sum * i) % n == 0 && (sum * i / n) % (n - i) == 0) {
                return true;
            }
        }
        return false;
    }
}

public class Main {
    public static void main(String[] args) {
        Problem p = new Problem();
        System.out.println(p.splitArraySameAverage(new int[]{1,2,3,4,5,6,7,8}));
        System.out.println(p.splitArraySameAverage(new int[]{3,1}));
    }
}

